/**
 * A beacon, as the desktop runs one: a responder keyed by the code that answers
 * with its address and says nothing else.
 *
 * The crypto is the real `respondToHandshake`, so this proves the browser's
 * lookup completes a genuine Noise IK handshake against an identity derived from
 * the code — not that it can parse a JSON string somebody handed it.
 */
function beacon(keys: StaticKeyPair, payload: string | null): { open: (url: string) => BinarySocketLike; urls: string[] } {
  const urls: string[] = []
  return {
    urls,
    open: (url) => {
      urls.push(url)
      const socket: BinarySocketLike = {
        send(data) {
          const opened = readSealedHandshake(Buffer.from(data), HANDSHAKE_OPEN_BYTES)
          if (!opened.ok) return
          const result = respondToHandshake(keys, opened.message, () => true)
          socket.onmessage?.({ data: withSealedVersion(result.reply) })
          if (payload === null) {
            socket.onclose?.({ code: 1000, reason: '' })
            return
          }
          socket.onmessage?.({ data: result.transport.send(Buffer.from(payload, 'utf8')) })
        },
        close: () => {},
        onopen: null,
        onmessage: null,
        onclose: null,
        onerror: null,
      }
      // The relay reaches the machine on the next turn, not on this one.
      setTimeout(() => socket.onopen?.(), 0)
      return socket
    },
  }
}

describe('looking a code up', () => {
  const CODE = 'H4K9-2FQT'
  const offer = JSON.stringify({
    t: 'machine',
    relayUrl: 'wss://relay.terminaldeck.dev',
    hostId: 'BBZFGL6PYFH6W23H5LGX4KERVZ',
    publicKey: 'NinFdauDs0+5UobA6Txvq2rhXZiyD1c4676VktxUN0A=',
  })

  it('reaches the machine showing that code and reads its address', async () => {
    const identity = await rendezvousIdentity(CODE)
    if (identity === null) throw new Error('the vector code did not derive an identity')
    const relay = beacon(identity.keys, offer)

    const found = await lookupMachine({ code: CODE, relayUrl: 'wss://relay.example', open: relay.open })
    expect(found?.hostId).toBe('BBZFGL6PYFH6W23H5LGX4KERVZ')
    expect(relay.urls).toEqual(['wss://relay.example/v1/join?host=' + identity.hostId])
  }, 30_000)

  it('finds nothing when the answering machine does not hold the code', async () => {
    // A relay that claimed the slot and answered for itself. Its handshake reply
    // cannot authenticate against a responder key derived from the code, so the
    // channel ends before the offer is ever parsed — which is the whole reason
    // the rendezvous is a sealed channel rather than a lookup table.
    const relay = beacon(generateStatic(), offer)
    expect(await lookupMachine({ code: CODE, relayUrl: 'wss://relay.example', open: relay.open })).toBeNull()
  }, 30_000)

  it('finds nothing when nobody is showing that code', async () => {
    const identity = await rendezvousIdentity(CODE)
    if (identity === null) throw new Error('the vector code did not derive an identity')
    const relay = beacon(identity.keys, null)
    expect(await lookupMachine({ code: CODE, relayUrl: 'wss://relay.example', open: relay.open })).toBeNull()
  }, 30_000)

  it('gives up rather than waiting forever on a relay that never answers', async () => {
    const open = (): BinarySocketLike => ({
      send: () => {},
      close: () => {},
      onopen: null,
      onmessage: null,
      onclose: null,
      onerror: null,
    })
    expect(
      await lookupMachine({ code: CODE, relayUrl: 'wss://relay.example', open, timeoutMs: 50 }),
    ).toBeNull()
  }, 30_000)
})
