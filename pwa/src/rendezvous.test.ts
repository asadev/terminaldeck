/**
 * Eight typed characters, and the machine they have to name.
 *
 * ## The vectors, and why they are the point of this file
 *
 * `rendezvousIdentity` here and `rendezvousIdentity` in
 * `src/main/remote/machines/rendezvous.ts` must produce the *same* host id and
 * the *same* responder key from the same code, or a person types a code
 * correctly and is told no machine is showing it. There is no shared module to
 * make that true by construction — the desktop's copy imports `node:scrypt` and
 * the desktop's own relay client, neither of which can be in a browser bundle —
 * so it is made true by something that fails on the drift instead.
 *
 * The two vectors below were generated by running the desktop's function. If
 * somebody changes the salt, the parameters or the seed layout on either side,
 * one of these stops matching. `shared/pairing-link.ts` restates the host-id
 * alphabet for the same reason and `relay-client.test.ts` cross-checks the
 * relay's own copy of the wire the same way: two implementations of one thing
 * are safe when something breaks on the difference, not when nobody edits either.
 *
 * `pwa/tests/node-crypto.test.ts` holds the other half — that the browser's
 * scrypt is byte-identical to Node's, at these parameters.
 */

import { describe, expect, it } from 'vitest'
import { HOST_SECRET_BYTES } from '../../src/shared/relay-wire'
import {
  generateStatic,
  respondToHandshake,
  type StaticKeyPair,
} from '../../src/shared/sealed'
import {
  HANDSHAKE_OPEN_BYTES,
  readSealedHandshake,
  withSealedVersion,
} from '../../src/shared/relay-wire'
import { hostKeyBytes } from './endpoint'
import { lookupMachine, parseOffer, rendezvousIdentity, RENDEZVOUS_SALT } from './rendezvous'
import type { BinarySocketLike } from './relay-socket'

/**
 * Generated by `rendezvousIdentity` in `src/main/remote/machines/rendezvous.ts`.
 *
 * To regenerate: call that function with the code and print `hostId` and
 * `keys.publicKey.toString('base64')`. Do not regenerate to make a failing test
 * pass — a change to these values is a change every already-shipped client
 * disagrees with.
 */
const VECTORS = [
  {
    code: 'H4K9-2FQT',
    hostId: 'ZWG39KXXW8GKVHZP6UF2SGUARD',
    publicKey: 'aQPhyoFeCJkVcrnoSvne9Eft2vkXQrmYitfzy2JowX8=',
  },
  {
    code: 'ABCD-EFGH',
    hostId: 'BBZFGL6PYFH6W23H5LGX4KERVZ',
    publicKey: 'NinFdauDs0+5UobA6Txvq2rhXZiyD1c4676VktxUN0A=',
  },
] as const

describe('the identity a code derives', () => {
  it('is pinned to the salt the desktop uses', () => {
    // Pinned to the literal in two places — here and in
    // `pwa/tests/node-crypto.test.ts` — because the desktop's own constant lives
    // in a module a browser build cannot import.
    expect(RENDEZVOUS_SALT).toBe('terminaldeck-machine-pairing-v1')
  })

  it('matches the desktop, host id and responder key', async () => {
    for (const vector of VECTORS) {
      const identity = await rendezvousIdentity(vector.code)
      expect(identity).not.toBeNull()
      expect(identity?.hostId).toBe(vector.hostId)
      expect(identity?.keys.publicKey.toString('base64')).toBe(vector.publicKey)
    }
  }, 20_000)

  it('lands on one identity however the code was typed', async () => {
    // The two ends derive from the *normalised* string, or pairing depends on
    // which keyboard somebody used. `O` folds to zero and `I`/`L` to one, which
    // is Crockford's own decoding rule.
    const canonical = await rendezvousIdentity('H4K9-2FQT')
    for (const typed of ['h4k92fqt', ' H4K9 2FQT ', 'H4K9—2FQT']) {
      expect((await rendezvousIdentity(typed))?.hostId).toBe(canonical?.hostId)
    }
  }, 30_000)

  it('refuses a string that is not a code, instead of hashing it anyway', async () => {
    for (const typed of ['', 'H4K9', 'H4K9-2FQTX', 'not a code at all']) {
      expect(await rendezvousIdentity(typed)).toBeNull()
    }
  })

  it('spends the first 32 bytes on the slot and the rest on the key', () => {
    // Stated as an assertion because the split is a wire fact: the desktop reads
    // the same seed the same way round, and swapping the halves would produce two
    // machines that both derive valid identities and never meet.
    expect(HOST_SECRET_BYTES).toBe(32)
  })
})

describe('the offer a machine answers with', () => {
  const offer = {
    t: 'machine',
    relayUrl: 'wss://relay.terminaldeck.dev',
    hostId: 'ZWG39KXXW8GKVHZP6UF2SGUARD',
    publicKey: 'NinFdauDs0+5UobA6Txvq2rhXZiyD1c4676VktxUN0A=',
    name: 'Asad’s MacBook Pro',
    platform: 'darwin',
  }

  it('reads the three facts that make an endpoint', () => {
    expect(parseOffer(JSON.stringify(offer))).toEqual({
      kind: 'relay',
      url: offer.relayUrl,
      hostId: offer.hostId,
      hostKey: offer.publicKey,
    })
  })

  it('accepts a key in standard base64, which is what the desktop sends', () => {
    // The regression this exists for: `isHostKey` in `shared/pairing-link.ts`
    // describes the base64url form a *link* carries and rejects `+` and `/`.
    // Validating an offer with it would refuse most real machines at random —
    // the vector above contains a `+` — and read on screen as a code that had
    // expired.
    expect(offer.publicKey).toContain('+')
    expect(hostKeyBytes(offer.publicKey)?.length).toBe(32)
    expect(parseOffer(JSON.stringify(offer))).not.toBeNull()
  })

  it('refuses anything that is not one', () => {
    expect(parseOffer('not json')).toBeNull()
    expect(parseOffer(JSON.stringify({ ...offer, t: 'something-else' }))).toBeNull()
    expect(parseOffer(JSON.stringify({ ...offer, hostId: 'lower-case-and-short' }))).toBeNull()
    expect(parseOffer(JSON.stringify({ ...offer, relayUrl: 'https://relay.example' }))).toBeNull()
    expect(parseOffer(JSON.stringify({ ...offer, publicKey: 'AAAA' }))).toBeNull()
    expect(parseOffer(JSON.stringify([offer]))).toBeNull()
  })

  it('will not hold an unbounded string on a hostile answer', () => {
    expect(parseOffer(`"${'x'.repeat(8192)}"`)).toBeNull()
  })
})

