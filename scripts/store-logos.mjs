#!/usr/bin/env node
/**
 * Fetch every store logo once, and write them into the app as bytes.
 *
 * ## Why the logos are fetched here and not in the store
 *
 * A store row is a claim about somebody else's project, and the mark on it is
 * the fastest way a person recognises which project. The obvious way to get one
 * on screen is `<img src="https://vendor.example/logo.svg">`, and it is the one
 * thing this file exists to prevent: an `<img>` pointed at a third-party host is
 * a request to that host **every time the store opens**, carrying an IP address
 * and a referrer to eighteen companies at once, and it draws nothing at all on a
 * laptop with no network. Neither is acceptable in a store whose whole argument
 * is that the bytes it offers were pinned in advance.
 *
 * So each mark is fetched **once, here, by hand**, and what the app ships is the
 * result. `src/renderer/store/logo-data.ts` is generated by this script and is
 * the only place those bytes live. At runtime the store reads a data URI out of
 * its own bundle; it opens the same offline as online and asks nobody anything.
 *
 * ## Why a generated module rather than files in a folder
 *
 * Because there is no other image in this renderer — not one `.png`, not one
 * `.svg`, checked before choosing — so files on disk would mean a new packaging
 * path (Vite emits some assets and inlines others under its 4 KB limit, and
 * `electron-builder.yml` would then be shipping two kinds of thing) invented for
 * a feature whose whole content is 42 small pictures. A module of data URIs is
 * one path: it is code, it is inside `out/**` like every other line of code, it
 * works identically in the app, in `vitest`, and in `.harness/stores.html`, and
 * there is nothing to forget to copy.
 *
 * The cost is a large generated file, and it is capped rather than hoped about:
 * {@link MAX_BYTES} refuses any single mark over 24 KB encoded, and the script
 * prints the total so the budget is a number somebody looked at.
 *
 * ## What is recorded, so this is auditable and refreshable
 *
 * Every row of {@link LOGOS} names the exact URL it was fetched from, and the
 * generated file carries that URL back with the sha256 of the bytes that came
 * back and the date they came back. That is what makes a refresh checkable:
 *
 * ```
 *   node scripts/store-logos.mjs --check   # re-fetch, compare, write nothing
 *   node scripts/store-logos.mjs           # re-fetch and rewrite the module
 * ```
 *
 * `--check` reports every mark whose upstream bytes have changed and exits
 * non-zero if any did. It is not in CI: it is a network call to twenty hosts,
 * and a red build because a vendor re-exported their SVG is a gate nobody would
 * keep. Run it when a logo looks wrong.
 *
 * GitHub sources are pinned to a **commit sha**, not a branch, so the URL in the
 * generated file resolves to the same bytes forever. Vendor sites cannot be
 * pinned that way, and for those the sha256 is the pin — which is the same
 * arrangement `browser-extension-catalogue.ts` makes for the release archives it
 * downloads, for the same reason.
 *
 * ## Trademarks
 *
 * These are third-party marks, used to identify the products the rows are
 * about. Nothing here is restyled, recoloured or redrawn — a mark is fetched
 * from its own project and scaled, and that is all. See the header of the
 * generated module, which says the same thing where somebody reading the app
 * will see it, including that a vendor asking for removal is honoured.
 *
 * ## Running it
 *
 * `node scripts/store-logos.mjs [--check] [--only <key>]`. It needs the network
 * and `sips`, which is macOS's own, for the raster half. It is not a test and
 * nothing in CI runs it.
 */
import { createHash } from 'node:crypto'
import { execFileSync } from 'node:child_process'
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

/** The widest a mark is ever drawn, times two for a retina panel. */
const RASTER_PX = 96

/** The fallback size, used only for a mark that is heavy at {@link RASTER_PX}. */
const SMALL_PX = 64

/** A vendor's own file is kept unscaled only up to here. */
const KEEP_PX = 160

/** Past this encoded, a mark is allowed to drop to {@link SMALL_PX}. */
const SOFT_CAP = 12_000

/** No single mark may exceed this encoded. A store is not a photo album. */
const MAX_BYTES = 24_000

