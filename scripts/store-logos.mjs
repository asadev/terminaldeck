/* ------------------------------------------------------------ fetching -- */

/**
 * A named agent, because two of these hosts refuse an unnamed one.
 *
 * Not a browser's string. A fetch that says what it is and where to complain is
 * the honest version of this, and it is the only header sent.
 */
const AGENT = 'terminaldeck-store-logos (+https://terminaldeck.dev)'

async function get(url) {
  const answer = await fetch(url, { redirect: 'follow', headers: { 'user-agent': AGENT } })
  if (!answer.ok) throw new Error(`${answer.status} ${answer.statusText}`)
  return Buffer.from(await answer.arrayBuffer())
}

/* ------------------------------------------------------------- shaping -- */

/**
 * An SVG, shrunk and made safe to embed.
 *
 * An `<img>` is already a sandbox — an SVG loaded through one cannot run script
 * and cannot fetch anything — but a store that pasted somebody else's
 * `<script>` into its own bundle would be shipping code it never read, so the
 * script tags and the `on*` handlers come out, and a mark that reaches for an
 * external URL is refused outright rather than shipped half-drawn.
 */
function shapeSvg(bytes) {
  let text = bytes.toString('utf8')
  text = text.replace(/<\?xml[\s\S]*?\?>/g, '')
  text = text.replace(/<!DOCTYPE[\s\S]*?>/gi, '')
  text = text.replace(/<!--[\s\S]*?-->/g, '')
  text = text.replace(/<script[\s\S]*?<\/script>/gi, '')
  text = text.replace(/\son[a-z]+\s*=\s*"[^"]*"/gi, '')
  text = text.replace(/>\s+</g, '><').trim()
  if (/(?:href|src)\s*=\s*["']https?:/i.test(text)) {
    throw new Error('this SVG loads something from the network; find another source')
  }
  if (!text.startsWith('<svg') && !/<svg[\s>]/.test(text)) throw new Error('not an SVG')
  return { mime: 'image/svg+xml', bytes: Buffer.from(text, 'utf8') }
}

/**
 * A raster mark at the smallest it can be drawn without looking it.
 *
 * Three candidates, and the smallest file wins: the vendor's own bytes (only if
 * they are already store-sized — nobody needs a 512px picture in a 40px tile),
 * and `sips` re-encodes at {@link RASTER_PX} and, for the stubborn ones,
 * {@link SMALL_PX}.
 *
 * The vendor's own file is in the running because `sips` frequently loses to
 * it: it writes full 8-bit RGBA, and a mark that shipped as a 16-colour palette
 * comes back **three times bigger** after being made smaller. Privacy Badger is
 * 4,907 bytes at 128px and 11 KB after a scale to 96. Re-encoding everything on
 * principle would have cost more than it saved on a third of this list.
 */
function shapeRaster(bytes, extension) {
  const scratch = mkdtempSync(join(tmpdir(), 'td-logo-'))
  try {
    const from = join(scratch, `in.${extension}`)
    writeFileSync(from, bytes)
    const measured = execFileSync('sips', ['-g', 'pixelWidth', '-g', 'pixelHeight', from], {
      encoding: 'utf8',
    })
    const side = Math.max(...[...measured.matchAll(/pixel(?:Width|Height): (\d+)/g)].map((m) => Number(m[1])))
    const candidates = []
    if (side > 0 && side <= KEEP_PX && extension === 'png') candidates.push(bytes)
    for (const px of [RASTER_PX, SMALL_PX]) {
      if (side > 0 && px >= side) continue
      const to = join(scratch, `out-${px}.png`)
      execFileSync('sips', ['-Z', String(px), '-s', 'format', 'png', from, '--out', to], {
        stdio: 'pipe',
      })
      candidates.push(readFileSync(to))
    }
    if (candidates.length === 0) candidates.push(bytes)
    /* Smallest wins, but only among the ones that are not absurd: a 64px
       re-encode is allowed to win only when the 96px one is genuinely heavy,
       so an ordinary mark keeps its resolution. */
    const best = candidates.reduce((a, b) => {
      const heavy = a.length * 1.37 > SOFT_CAP
      return heavy && b.length < a.length ? b : a.length <= b.length ? a : b
    })
    return { mime: 'image/png', bytes: best }
  } finally {
    rmSync(scratch, { recursive: true, force: true })
  }
}

function shape(bytes, url) {
  if (bytes.subarray(0, 400).toString('utf8').includes('<svg') || url.endsWith('.svg')) {
    return shapeSvg(bytes)
  }
  const extension = url.endsWith('.png') || bytes.subarray(1, 4).toString() === 'PNG' ? 'png' : 'img'
  return shapeRaster(bytes, extension)
}

/* -------------------------------------------------------------- writing -- */

const HEADER = `/**
 * Every store logo, as bytes this app already has.
 *
 * **Generated by \`scripts/store-logos.mjs\`. Do not edit by hand** — run the
 * script, which re-fetches from the URLs recorded on each entry.
 *
 * ## Why the marks are in here rather than at the end of a URL
 *
 * Because \`<img src="https://vendor.example/logo.svg">\` is a request to a third
 * party every single time the store is opened — an IP address and a referrer
 * handed to twenty companies for the privilege of drawing a picture — and
 * because it draws nothing on an aeroplane. Neither belongs in a store whose
 * whole argument is that what it offers was pinned in advance. Each mark was
 * fetched once, by hand, and what ships is the result: the store reads these out
 * of its own bundle and asks nobody anything.
 *
 * ## What each entry can be checked against
 *
 * \`source\` is exactly where the bytes came from, \`sha256\` is what came back,
 * and \`fetched\` is when. GitHub sources are pinned to a commit sha, so the URL
 * resolves to the same bytes forever; for a vendor's own site the sha256 is the
 * pin. \`node scripts/store-logos.mjs --check\` re-fetches every one and names
 * any whose upstream bytes have moved.
 *
 * ## Trademarks
 *
 * **These are third-party trademarks, reproduced to identify the products the
 * store's rows are about.** Terminal Deck claims no rights in any of them and is
 * not endorsed by, affiliated with, or a partner of any of these projects or
 * companies. Every mark is the vendor's own file, scaled and nothing else — none
 * is recoloured, redrawn, cropped or combined with anything. A vendor who would
 * rather their mark were not shown here only has to say so: open an issue and it
 * comes out, and the row falls back to the generated monogram in
 * \`StoreLogo.tsx\`, which is this app's own drawing and identifies nobody's
 * brand but its own.
 */

/** One mark: the bytes, and the provenance that makes them checkable. */
export interface StoreLogoAsset {
  /** The mark itself, inline. Never a network address. */
  readonly src: string
  /** Exactly where it was fetched from. */
  readonly source: string
  /** sha256 of what came back from {@link source}, before scaling. */
  readonly sha256: string
  /** The day it came back, ISO. */
  readonly fetched: string
  /**
   * Whether this mark needs a light tile behind it.
   *
   * True only for a mark its vendor drew in one dark ink for a light page —
   * GitHub's Invertocat, Context7's wordmark. Without it they are invisible in
   * the dark theme. The tile is a background; the mark itself is untouched.
   */
  readonly plate: boolean
}
`

async function main() {
  const argv = process.argv.slice(2)
  const check = argv.includes('--check')
  const onlyAt = argv.indexOf('--only')
  const only = onlyAt === -1 ? '' : argv[onlyAt + 1]
  const today = new Date().toISOString().slice(0, 10)
  const wanted = only === '' ? LOGOS : LOGOS.filter((one) => one.key === only)

  const out = []
  const problems = []
  let total = 0
  for (const logo of wanted) {
    try {
      const raw = await get(logo.url)
      const sha256 = createHash('sha256').update(raw).digest('hex')
      const shaped = shape(raw, logo.url)
      const src = `data:${shaped.mime};base64,${shaped.bytes.toString('base64')}`
      if (src.length > MAX_BYTES) {
        throw new Error(`${src.length} bytes encoded, over the ${MAX_BYTES} cap`)
      }
      total += src.length
      out.push({ key: logo.key, src, source: logo.url, sha256, fetched: today, plate: logo.plate === true })
      console.log(`  ok  ${logo.key.padEnd(24)} ${String(raw.length).padStart(7)} → ${String(src.length).padStart(6)}  ${sha256.slice(0, 12)}`)
    } catch (error) {
      problems.push(`${logo.key}: ${error instanceof Error ? error.message : String(error)}`)
      console.log(`  FAIL ${logo.key}: ${error instanceof Error ? error.message : String(error)}`)
    }
  }

  console.log(`\n  ${out.length}/${wanted.length} marks, ${total.toLocaleString('en-US')} bytes encoded in total`)

  if (check) {
    const current = new URL('../src/renderer/store/logo-data.ts', import.meta.url)
    const text = readFileSync(current, 'utf8')
    let moved = 0
    for (const one of out) {
      if (!text.includes(one.sha256)) {
        console.log(`  MOVED ${one.key} — upstream is now ${one.sha256}`)
        moved += 1
      }
    }
    console.log(moved === 0 ? '  nothing has moved' : `  ${moved} moved`)
    process.exit(moved === 0 && problems.length === 0 ? 0 : 1)
  }

  if (problems.length > 0) {
    console.error('\nrefusing to write: ' + problems.join('; '))
    process.exit(1)
  }
  if (only !== '') {
    console.error('\n--only is for looking, not for writing; run without it to regenerate')
    process.exit(1)
  }

  const body = out
    .map(
      (one) =>
        `  '${one.key}': {\n` +
        `    src: '${one.src}',\n` +
        `    source: '${one.source}',\n` +
        `    sha256: '${one.sha256}',\n` +
        `    fetched: '${one.fetched}',\n` +
        `    plate: ${one.plate},\n` +
        `  },`,
    )
    .join('\n')
  const file =
    HEADER +
    '\n/** Every mark, by the key a catalogue row names in its `logo` field. */\n' +
    'export const STORE_LOGO_ASSETS: Readonly<Record<string, StoreLogoAsset>> = {\n' +
    body +
    '\n}\n'
  writeFileSync(new URL('../src/renderer/store/logo-data.ts', import.meta.url), file)
  console.log('  wrote src/renderer/store/logo-data.ts')
}

await main()
